import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { once } from 'node:events';
import { readFileSync } from 'node:fs';
import { createServer } from 'node:http';
import { test } from 'node:test';
import {
  reportTranscript,
  verifyComposeMeasurement,
  type AttestationReport,
} from '../src/index.js';
import { REPORT } from './fixtures.js';

interface Evidence {
  quote: string;
  event_log: string;
  app_compose: string;
}
interface Event {
  imr: number;
  event: string;
  event_payload: string;
}
const recorded = JSON.parse(
  readFileSync(new URL('../../test/fixtures/dstack_v1_attestation.json', import.meta.url), 'utf8'),
) as {
  nonce: string;
  captured_at: string;
  report: AttestationReport;
  pccs_responses: {
    url: string;
    status: number;
    headers: Record<string, string>;
    body_base64: string;
  }[];
};
const fixture = JSON.parse(
  readFileSync(new URL('../../test/fixtures/dstack_event_vectors.json', import.meta.url), 'utf8'),
) as {
  vectors: {
    name: string;
    events: unknown[];
    app_compose: string;
    compose_hash: string;
    rtmr3: string;
    valid: boolean;
  }[];
};

// Generated by the pinned Rust cc-eventlog and consumed by both suites.
for (const vector of fixture.vectors) {
  test(`upstream event parity: ${vector.name}`, async () => {
    const report = structuredClone(REPORT);
    const quote = Buffer.alloc(568);
    quote.set(Buffer.from(vector.rtmr3, 'hex'), 520);
    report.attestation.evidence = {
      quote: quote.toString('hex'),
      event_log: JSON.stringify(vector.events),
      app_compose: vector.app_compose,
    };
    const result = await verifyComposeMeasurement(report);
    assert.equal(result.ok, vector.valid, JSON.stringify(result));
    assert.equal(result.composeHash, vector.valid ? vector.compose_hash : undefined);
  });
}

test('vendor-valid recorded quote rejects forged compose payload without changing quote or digests', async (t) => {
  // Verify real quote signatures, vendor roots and report_data offline using
  // the recorded collateral and its capture time.
  const now = Math.floor(Date.parse(recorded.captured_at) / 1000);
  t.mock.method(Date, 'now', () => now * 1000);
  const responses = new Map(
    recorded.pccs_responses.map((response) => {
      const url = new URL(response.url);
      return [url.pathname + url.search, response];
    }),
  );
  const server = createServer((request, response) => {
    const saved = responses.get(request.url ?? '');
    if (!saved) {
      response.writeHead(404).end();
      return;
    }
    response.writeHead(saved.status, saved.headers);
    response.end(Buffer.from(saved.body_base64, 'base64'));
  });
  t.after(
    () =>
      new Promise<void>((resolve, reject) => {
        server.close((error) => (error ? reject(error) : resolve()));
        server.closeAllConnections();
      }),
  );
  const listening = once(server, 'listening');
  server.listen(0, '127.0.0.1');
  await listening;
  const address = server.address();
  assert.ok(address && typeof address === 'object');
  const options = { now, pccsUrl: `http://127.0.0.1:${address.port}` };
  const original = await reportTranscript(recorded.report, recorded.nonce, options);
  for (const id of ['id-1', 'id-2', 'id-3', 'id-4']) {
    assert.equal(
      original.lines.find((line) => line.id === id)?.status,
      'pass',
      JSON.stringify(original),
    );
  }
  const report = structuredClone(recorded.report);
  const evidence = report.attestation.evidence as Evidence;
  const events = JSON.parse(evidence.event_log) as Event[];
  const compose = events.find((event) => event.imr === 3 && event.event === 'compose-hash');
  assert.ok(compose);
  evidence.app_compose += '\n';
  compose.event_payload = createHash('sha256').update(evidence.app_compose).digest('hex');
  evidence.event_log = JSON.stringify(events);
  const forged = await reportTranscript(report, recorded.nonce, options);
  assert.equal(forged.lines.find((line) => line.id === 'id-1')?.status, 'pass');
  const measurement = forged.lines.find((line) => line.id === 'id-4');
  assert.equal(measurement?.status, 'fail');
  assert.match(measurement?.detail ?? '', /digest does not match/);
  assert.equal(forged.composeHash, undefined);
  assert.equal(forged.verdict.verified, false);
  assert.match(forged.verdict.line, /^NOT VERIFIED/);
});
