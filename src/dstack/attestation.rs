use std::io::Cursor;

use dcap_qvl::quote::{Quote as DcapQuote, Report};
use serde::{de::IgnoredAny, Deserialize, Serialize};

use crate::aci::keys::{KeyError, Quote};
use crate::aci::verifier::dcap_report_data;

// This is the subset of the dstack MessagePack V1 schema used by the gateway.
// Keep the event field encodings aligned with upstream cc-eventlog::tdx::TdxEvent.
#[derive(Deserialize)]
struct Attestation {
    version: u64,
    platform: Platform,
    stack: Stack,
}

#[derive(Deserialize)]
#[serde(tag = "kind", content = "data", rename_all = "kebab-case")]
enum Platform {
    Tdx {
        quote: Vec<u8>,
        event_log: Vec<TdxEvent>,
    },
    GcpTdx(IgnoredAny),
    SevSnp(IgnoredAny),
    NitroEnclave(IgnoredAny),
    AwsNitroTpm(IgnoredAny),
}

#[derive(Deserialize)]
#[serde(tag = "kind", content = "data", rename_all = "kebab-case")]
enum Stack {
    Dstack {
        report_data: Vec<u8>,
        config: String,
    },
}

#[derive(Deserialize, Serialize)]
struct TdxEvent {
    imr: u32,
    event_type: u32,
    #[serde(with = "serde_human_bytes", default)]
    digest: Vec<u8>,
    event: String,
    #[serde(with = "serde_human_bytes")]
    event_payload: Vec<u8>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    version: Option<u32>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    preimage: Option<String>,
}

pub(super) fn decode_tdx_quote(bytes: &[u8], expected: [u8; 64]) -> Result<Quote, KeyError> {
    // Same size limit and MessagePack map prefix check as dstack's decoder.
    if bytes.len() > 10 * 1024 * 1024 || !matches!(bytes.first(), Some(0x80..=0x8f | 0xde | 0xdf)) {
        return Err(KeyError::Quote("invalid dstack Attest envelope".into()));
    }
    let mut input = Cursor::new(bytes);
    let attestation = Attestation::deserialize(&mut rmp_serde::Deserializer::new(&mut input))
        .map_err(|e| KeyError::Quote(format!("invalid dstack Attest MessagePack: {e}")))?;
    if input.position() != bytes.len() as u64 || attestation.version != 1 {
        return Err(KeyError::Quote(
            "invalid dstack Attest version or trailing bytes".into(),
        ));
    }
    let (raw_quote, event_log) = match attestation.platform {
        Platform::Tdx { quote, event_log } => (quote, event_log),
        Platform::GcpTdx(_) => return Err(unsupported_variant("DstackGcpTdx (gcp-tdx)")),
        Platform::SevSnp(_) => return Err(unsupported_variant("DstackAmdSevSnp (sev-snp)")),
        Platform::NitroEnclave(_) => {
            return Err(unsupported_variant("DstackNitroEnclave (nitro-enclave)"));
        }
        Platform::AwsNitroTpm(_) => {
            return Err(unsupported_variant("DstackAwsNitroTpm (aws-nitro-tpm)"));
        }
    };
    let Stack::Dstack {
        report_data,
        config,
    } = attestation.stack;
    let quote = DcapQuote::parse(&raw_quote)
        .map_err(|e| KeyError::Quote(format!("invalid TDX quote in dstack Attest: {e}")))?;
    if !matches!(quote.report, Report::TD10(_) | Report::TD15(_)) {
        return Err(KeyError::Quote(
            "dstack Attest tdx evidence has a non-TDX DCAP report".into(),
        ));
    }
    if report_data != expected || dcap_report_data(&quote.report) != &expected {
        return Err(KeyError::Quote("dstack Attest report_data mismatch".into()));
    }
    let event_log = serde_json::to_string(&event_log)
        .map_err(|e| KeyError::Quote(format!("serialize dstack event log: {e}")))?;
    Ok(Quote {
        raw_quote,
        report_data,
        event_log: serde_json::Value::String(event_log),
        vm_config: serde_json::Value::String(config),
        app_compose: None,
    })
}

// The gateway logs KeyError details internally and returns a generic public error.
fn unsupported_variant(variant: &str) -> KeyError {
    KeyError::Quote(format!(
        "dstack Attest returned unsupported TEE variant {variant}"
    ))
}

#[cfg(test)]
mod tests {
    use dstack_sdk::dstack_client_v1::AttestResponse;
    use serde_json::{json, Value};

    use super::decode_tdx_quote;

    const RECORDED_ATTEST: &str =
        include_str!("../../tests/fixtures/dstack/tdx-lite-v1-attest.json");
    const REPORT_DATA: [u8; 64] = [0x42; 64];

    fn recorded_attestation() -> AttestResponse {
        serde_json::from_str(RECORDED_ATTEST).unwrap()
    }

    #[test]
    fn preserves_v2_event_digest_and_preimage() {
        // The app-id vector generated by upstream cc-eventlog at dad8326f
        // in PR #531, paired with the TDX quote from the recorded response.
        let event = json!({
            "imr": 3,
            "event_type": 134217729,
            "digest": "f3fdf5a4af4b5554d2fd20456bd667fce7df585c5d94a4f36b5c16ae22eab4123bf6f4e97a30efb6ec980a950e28d1a8",
            "event": "app-id",
            "event_payload": "1111111111111111111111111111111111111111",
            "version": 2,
            "preimage": "7b226e616d65223a226170702d6964222c227061796c6f6164223a2231313131313131313131313131313131313131313131313131313131313131313131313131313131222c2274797065223a3133343231373732397d",
        });
        let mut binary_event = event.clone();
        for field in ["digest", "event_payload"] {
            binary_event[field] = json!(hex::decode(event[field].as_str().unwrap()).unwrap());
        }
        let recorded = decode_tdx_quote(&recorded_attestation().attestation, REPORT_DATA).unwrap();
        let bytes = rmp_serde::to_vec_named(&json!({
            "version": 1,
            "platform": {"kind": "tdx", "data": {"quote": recorded.raw_quote, "event_log": [binary_event]}},
            "stack": {"kind": "dstack", "data": {"report_data": REPORT_DATA.to_vec(), "config": "{}"}},
        }))
        .unwrap();
        let quote = decode_tdx_quote(&bytes, REPORT_DATA).unwrap();
        let events: Value = serde_json::from_str(quote.event_log.as_str().unwrap()).unwrap();
        assert_eq!(events, json!([event]));
    }

    #[test]
    fn rejects_unsupported_tee_variants_by_name() {
        for (kind, variant) in [
            ("gcp-tdx", "DstackGcpTdx"),
            ("sev-snp", "DstackAmdSevSnp"),
            ("nitro-enclave", "DstackNitroEnclave"),
            ("aws-nitro-tpm", "DstackAwsNitroTpm"),
        ] {
            let bytes = rmp_serde::to_vec_named(&json!({
                "version": 1,
                "platform": {"kind": kind, "data": {}},
                "stack": {"kind": "dstack", "data": {"report_data": REPORT_DATA.to_vec(), "config": "{}"}},
            }))
            .unwrap();
            let error = decode_tdx_quote(&bytes, REPORT_DATA).unwrap_err();
            assert_eq!(
                error.to_string(),
                format!("quote provider failure: dstack Attest returned unsupported TEE variant {variant} ({kind})")
            );
        }
    }

    #[test]
    fn rejects_mismatched_report_data_and_trailing_bytes() {
        let mut response = recorded_attestation();
        let error = decode_tdx_quote(&response.attestation, [0x43; 64]).unwrap_err();
        assert!(error.to_string().contains("report_data mismatch"));

        response.attestation.push(0);
        let error = decode_tdx_quote(&response.attestation, REPORT_DATA).unwrap_err();
        assert!(error.to_string().contains("trailing bytes"));
    }
}
